create table if not exists public.bill_change_requests (
  id bigint generated by default as identity primary key,
  booking_code text not null,
  requested_change text not null,
  details text not null,
  created_at timestamptz not null default now()
);

alter table public.bill_change_requests enable row level security;

drop policy if exists "Allow bill change requests" on public.bill_change_requests;
create policy "Allow bill change requests"
on public.bill_change_requests
for insert
to anon, authenticated
with check (true);

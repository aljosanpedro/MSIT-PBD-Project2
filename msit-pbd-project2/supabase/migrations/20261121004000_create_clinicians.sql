create table if not exists public.clinicians (
  id bigint generated by default as identity primary key,
  name text not null unique,
  role text not null,
  description text not null,
  days_available text not null,
  times_available text not null,
  created_at timestamptz not null default now()
);

alter table public.clinicians enable row level security;

create policy "Anyone can view clinicians"
on public.clinicians
for select
to anon, authenticated
using (true);

with
  first_names(name) as (
    values
      ('Maria'),
      ('Paolo'),
      ('Ana'),
      ('Elena'),
      ('Miguel'),
      ('Sofia'),
      ('Daniel'),
      ('Isabella'),
      ('Rafael'),
      ('Camille')
  ),
  last_names(name) as (
    values
      ('Santos'),
      ('Reyes'),
      ('Cruz'),
      ('Garcia'),
      ('Lim'),
      ('Villanueva'),
      ('Dela Cruz'),
      ('Navarro'),
      ('Mendoza'),
      ('Aquino')
  ),
  numbered_profiles as (
    select
      row_number() over (order by first_names.name, last_names.name) as profile_number,
      first_names.name as first_name,
      last_names.name as last_name
    from first_names
    cross join last_names
  )
insert into public.clinicians (
  name,
  role,
  description,
  days_available,
  times_available
)
select
  'Dr. ' || first_name || ' ' || last_name,
  (array[
    'Clinical Psychologist',
    'Psychiatrist',
    'Counseling Therapist',
    'Behavioral Therapist',
    'Clinical Counselor',
    'Family Therapist'
  ])[((profile_number - 1) % 6) + 1],
  (array[
    'Provides compassionate support for anxiety, stress, and personal growth.',
    'Helps clients understand their mental health and find practical paths toward wellness.',
    'Supports individuals and families through life transitions and relationship concerns.',
    'Works with clients on healthy routines, coping strategies, and emotional resilience.',
    'Offers a supportive space for self-discovery, adjustment, and personal development.',
    'Helps families strengthen communication and navigate challenging experiences together.'
  ])[((profile_number - 1) % 6) + 1],
  (array[
    'Monday - Friday',
    'Monday, Wednesday, Friday',
    'Tuesday - Saturday',
    'Monday - Thursday',
    'Wednesday - Sunday'
  ])[((profile_number - 1) % 5) + 1],
  (array[
    '8:00 AM - 5:00 PM',
    '9:00 AM - 6:00 PM',
    '10:00 AM - 7:00 PM',
    '8:00 AM - 4:00 PM',
    '11:00 AM - 8:00 PM'
  ])[((profile_number - 1) % 5) + 1]
from numbered_profiles
on conflict (name) do nothing;

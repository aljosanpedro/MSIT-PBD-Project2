create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text not null,
  question_type text not null,
  question text not null,
  file_url text,
  created_at timestamptz not null default now()
);

alter table public.questions enable row level security;

drop policy if exists "Allow question submissions" on public.questions;
create policy "Allow question submissions"
on public.questions
for insert
to anon, authenticated
with check (true);

insert into storage.buckets (id, name, public)
values ('question-files', 'question-files', true)
on conflict (id) do update set public = true;

drop policy if exists "Allow question file uploads" on storage.objects;
create policy "Allow question file uploads"
on storage.objects
for insert
to anon, authenticated
with check (bucket_id = 'question-files');

drop policy if exists "Allow question file reads" on storage.objects;
create policy "Allow question file reads"
on storage.objects
for select
to anon, authenticated
using (bucket_id = 'question-files');
